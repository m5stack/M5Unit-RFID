void loop()
{
    M5.update();
    auto touch = M5.Touch.getDetail();

    // Read NFC data
    if (M5.BtnA.wasClicked() || touch.wasClicked()) {
        if (unit.detectIdleDevice()) {
            UID uid{};
            if (unit.activateDevice(uid)) {
                M5.Speaker.tone(1000, 20);
                M5_LOGI("UID:%s %s", uid.uidAsString().c_str(), uid.typeAsString().c_str());

                if (uid.canNFC()) {
                    nfc_read(uid);
                    // unit.dumpDevice(uid);
                } else {
                    M5_LOGE("This device can not support NFC");
                }

                unit.deactivateDevice();
            }
        }
    }
    // Write NFC data
    else if (M5.BtnA.isHolding() || touch.isHolding()) {
        if (unit.detectIdleDevice()) {
            UID uid{};
            if (unit.activateDevice(uid)) {
                if (uid.canNFC()) {
                    M5.Speaker.tone(2000, 20);
                    M5_LOGI("UID:%s %s", uid.uidAsString().c_str(), uid.typeAsString().c_str());

                    nfc_write(uid);
                    // nfc_write_png(uid);
                    //  unit.dumpDevice(uid);

                } else {
                    M5_LOGE("This device can not support NFC");
                }
                unit.deactivateDevice();
            }
        }
    }
}
