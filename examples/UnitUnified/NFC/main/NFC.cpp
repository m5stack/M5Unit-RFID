void setup()
{
    M5.begin();

    auto pin_num_sda = M5.getPin(m5::pin_name_t::port_a_sda);
    auto pin_num_scl = M5.getPin(m5::pin_name_t::port_a_scl);
    M5_LOGI("getPin: SDA:%u SCL:%u", pin_num_sda, pin_num_scl);
    Wire.begin(pin_num_sda, pin_num_scl, 100 * 1000U);

    if (!Units.add(unit, Wire) || !Units.begin()) {
        M5_LOGE("Failed to begin");
        lcd.clear(TFT_RED);
        while (true) {
            m5::utility::delay(10000);
        }
    }

    M5_LOGI("M5UnitUnified has been begun");
    M5_LOGI("%s", Units.debugInfo().c_str());

    if (lcd.width() < lcd.height()) {
        lcd.setRotation(1);
    }
    if (lcd.height() < 240) {
        lcd.setFont(&fonts::Font0);
    } else {
        lcd.setFont(&fonts::Font2);
    }
    lcd.clear(0);
    lcd.setCursor(8, 0);
    lcd.printf("Please put the devices");
    M5_LOGI("Please put the devices");
}

void nfc_read(const UID& uid)
{
    uint8_t rbuf[1024]{};
    uint32_t sz{};

    if (!unit.mifareRequiredSizeNDEF(uid, sz)) {
        M5_LOGE("Failed to read");
        return;
    }
    M5_LOGI("Required size:%u", sz);

    if (sz > m5::stl::size(rbuf)) {
        M5_LOGE("Not enough buffer %u", sz);
        return;
    }

    lcd.clear();
    lcd.setCursor(0, lcd.fontHeight());
    lcd.printf("UID:%s %s\n", uid.uidAsString().c_str(), uid.typeAsString().c_str());

    auto result = unit.mifareReadNDEF(uid, rbuf, sz);
    if (!result) {
        M5_LOGE("Failed to read %02X", result.error());
        return;
    }
    M5_LOGI("Read:%u", sz);
    // M5_DUMPI(rbuf, sz);

    uint32_t offset{};
    Message msg{};
    do {
        auto decoded = msg.decode(rbuf + offset, sz - offset);
        if (!decoded) {
            M5_LOGE("Failed to decode");
            break;
        }
        offset += decoded;
        M5_LOGI("Decoded:%u", decoded);

        msg.dump();

        if (msg.isNDEFMessage()) {
            for (auto&& r : msg.records()) {
                if (r.tnf() == TNF::Wellknown) {
                    auto s = r.payloadAsString().c_str();
                    M5_LOGI("R:%u TNF:%u T:%s [%s]", r.required(), r.tnf(), r.type(), s);
                    lcd.printf("T:%s [%s]\n", r.type(), s);
                }
            }
        }
    } while (!msg.isTerminator());
}

void nfc_write(const UID& uid)
{
    Message msg{};      // NDEFMessage as default
    Record r0{}, r1{};  // Wellknown as default

    // URI Record
    r0.setURIPayload("https://m5stack.com/", URIProtocol::HTTPS);

    // Text Reacord (need langage type)
    // const char* en_data = "Hello M5Stack";
    // r1.setTextPayload(en_data, "en");
    // const char* ja_data = "こんにちは M5Stack";
    // r1.setTextPayload(ja_data, "ja");
    const char* zh_data = "你好 M5Stack";
    r1.setTextPayload(zh_data, "zh");

    msg.push_back(r0);
    msg.push_back(r1);

    // Encode
    uint8_t buf[1024]{};
    if (msg.required() > m5::stl::size(buf)) {
        M5_LOGE("Not enough buffer");
        return;
    }
    auto encoded = msg.encode(buf, m5::stl::size(buf));
    if (encoded == 0) {
        M5_LOGE("Failed to encode");
        return;
    }

    M5_LOGI("Write length: %u", encoded);
    // M5_DUMPI(buf, encoded);

    // Write (and Change formatif  UltraLight/C)
    // true if NATG or NTAG format Light/C already exists
    if (unit.mifareWriteChangeToNTAGFormat(uid)) {
        auto result = unit.mifareWriteNDEF(uid, buf, encoded);
        if (result) {
            M5_LOGI("Write OK");
        } else {
            M5_LOGI("Write NG:%02X", result.error());
        }
    } else {
        M5_LOGE("Failed to changeToNTAGFormat");
    }
}

