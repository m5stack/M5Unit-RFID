// Need large user area (NATG216)
void nfc_write_png(const UID& uid)
{
    Message msg{};
    Record r{TNF::Media};  // using MIME
    r.setType("image/png");
    r.setPayload(poji_64_png, poji_64_png_len);
    msg.push_back(r);

    // Encode
    uint8_t buf[1024]{};
    if (msg.required()  > m5::stl::size(buf)) {
        M5_LOGE("Not enough buffer");
        return;
    }
    auto encoded = msg.encode(buf, m5::stl::size(buf));
    if (encoded == 0) {
        M5_LOGE("Failed to encode");
        return;
    }
    M5_LOGI("Write length: %u", encoded);
    //    M5_DUMPI(buf, encoded);

    if (unit.mifareWriteChangeToNTAGFormat(uid)) {
        auto result = unit.mifareWriteNDEF(uid, buf, encoded);
        if (result) {
            M5_LOGI("Write OK");
        } else {
            M5_LOGI("Write NG:%02X", result.error());
        }
    } else {
        M5_LOGE("Failed to changeToNTAGFormat");
    }
}

